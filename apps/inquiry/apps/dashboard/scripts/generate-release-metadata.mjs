import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dashboardRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = resolve(dashboardRoot, "../..");
const output = resolve(dashboardRoot, "functions/_generated/release.ts");

function git(...args) {
  return execFileSync("git", args, { cwd: repositoryRoot, encoding: "utf8" }).trim();
}

const releaseSha = (process.env.GITHUB_SHA || process.env.RELEASE_SHA || git("rev-parse", "HEAD"))
  .trim()
  .toLowerCase();
if (!/^[0-9a-f]{40}$/.test(releaseSha)) {
  throw new Error("Release SHA must be a 40-character Git commit SHA");
}

const builtAt = process.env.RELEASE_BUILT_AT || new Date().toISOString();
if (Number.isNaN(Date.parse(builtAt))) throw new Error("Release build time must be ISO-8601");

mkdirSync(dirname(output), { recursive: true });
writeFileSync(
  output,
  `// Generated by scripts/generate-release-metadata.mjs; do not edit.\n` +
    `export const RELEASE_METADATA = ${JSON.stringify({
      application: "inquiry",
      release_sha: releaseSha,
      built_at: builtAt,
      contract_version: 1,
    })} as const;\n`,
);
